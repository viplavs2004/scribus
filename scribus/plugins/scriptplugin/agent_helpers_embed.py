#!/usr/bin/env python3
"""Regenerates agent_helpers_py.h from agent_helpers.py.

agent_helpers.py holds the Python helpers that are made available to scripts run by the AI
agent (Unicode <-> Kruti Dev conversion and the text-frame functions built on it). The
scripter plugin has no resource directory of its own, so the source is embedded in the plugin
as a string. Run this after editing agent_helpers.py:

    python agent_helpers_embed.py

Non-ASCII characters are written as unicode escapes, so the result does not depend on the
encoding the C++ compiler assumes. MSVC limits a string literal to about 16 KB, so the source
is split into several adjacent raw string literals at line boundaries.
"""
import os

BACKSLASH = chr(92)
CHUNK = 12000
DELIM = "PYHELPERS"

here = os.path.dirname(os.path.abspath(__file__))
SOURCES = ["agent_helpers.py", "agent_notices.py"]        # embedded in this order, as one module
parts = []
for name in SOURCES:
    with open(os.path.join(here, name), encoding="utf-8") as f:
        parts.append(f.read().replace("\r\n", "\n"))
source = "\n\n".join(parts)

escaped = []
for ch in source:
    code = ord(ch)
    if code < 128:
        escaped.append(ch)
    elif code < 0x10000:
        escaped.append(BACKSLASH + "u%04x" % code)
    else:
        escaped.append(BACKSLASH + "U%08x" % code)
source = "".join(escaped)

assert (")" + DELIM + '"') not in source
# MSVC accepts at most 65535 bytes in one concatenated string literal
assert len(source) < 60000, 'the embedded helpers are too big for one string literal: split them into two arrays'

chunks = []
current = []
size = 0
for line in source.splitlines(keepends=True):
    if size + len(line) > CHUNK and current:
        chunks.append("".join(current))
        current, size = [], 0
    current.append(line)
    size += len(line)
if current:
    chunks.append("".join(current))

out = [
    "// Generated by agent_helpers_embed.py from agent_helpers.py. Do not edit by hand.",
    "#ifndef AGENT_HELPERS_PY_H",
    "#define AGENT_HELPERS_PY_H",
    "",
    "static const char kAgentHelpersSource[] =",
]
for k, chunk in enumerate(chunks):
    end = ";" if k == len(chunks) - 1 else ""
    out.append('R"' + DELIM + "(" + chunk + ")" + DELIM + '"' + end)
out += ["", "#endif", ""]

with open(os.path.join(here, "agent_helpers_py.h"), "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(out))
print("wrote agent_helpers_py.h:", len(chunks), "chunks,", len(source), "characters")
